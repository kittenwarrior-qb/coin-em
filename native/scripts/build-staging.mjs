import { execFileSync } from 'node:child_process'
import { readFile, writeFile, mkdir, copyFile, lstat, cp, symlink } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { inventory, hash } from './policy.mjs'
import { stagingApi, stagingRoot, stagingConfig, validateStagingReceipt } from './staging-policy.mjs'

// Only called explicitly by the owned Android fixture; no arbitrary API/env-file support.
const [rootArg, portArg] = process.argv.slice(2)
const output = await stagingRoot(rootArg ?? ''), port = Number(portArg), api = stagingApi(port)
const project = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..'), fe = path.join(project, 'fe')
const base = JSON.parse(await readFile(path.join(project, 'native/capacitor.config.json'), 'utf8'))
const config = stagingConfig(base), web = path.join(output, 'assets/public'), resources = path.join(output, 'res')
try { await lstat(path.join(output, 'assets')); throw Error('QA_ASSETS_ALREADY_EXIST') } catch (error) { if (error.code !== 'ENOENT') throw error }
await mkdir(web, { recursive: true }); await mkdir(path.join(resources, 'raw'), { recursive: true }); await mkdir(path.join(resources, 'xml'), { recursive: true })
// Keep the unchanged optimizer's strict <root>/dist boundary. Never bypass its guard
// or build over the shared frontend dist. No .env, credentials or node_modules copy.
const frontend = path.join(output, 'frontend')
await mkdir(frontend)
for (const directory of ['src', 'public', 'pwa']) await cp(path.join(fe, directory), path.join(frontend, directory), { recursive: true })
for (const file of ['package.json', 'package-lock.json', 'vite.config.ts', 'index.html', 'tsconfig.json', 'tsconfig.app.json', 'tsconfig.node.json']) await copyFile(path.join(fe, file), path.join(frontend, file))
await symlink(path.join(fe, 'node_modules'), path.join(frontend, 'node_modules'), process.platform === 'win32' ? 'junction' : 'dir')
const env = Object.fromEntries(Object.entries(process.env).filter(([key]) => !key.startsWith('VITE_')))
Object.assign(env, { NODE_ENV: 'production', VITE_NATIVE_APP: 'true', VITE_USE_HASH_ROUTE: 'true', VITE_BASE_URL: '/', VITE_API_URL: api })
execFileSync(process.execPath, [path.join(fe, 'node_modules/vite/bin/vite.js'), 'build', '--mode', 'native'], { cwd: frontend, env, stdio: 'inherit', windowsHide: true })
await cp(path.join(frontend, 'dist'), web, { recursive: true })
const index = path.join(web, 'index.html')
await writeFile(index, (await readFile(index, 'utf8')).replace(/\s*<link\s+rel="manifest"[^>]*>/g, '').replace('width=device-width, initial-scale=1.0', 'width=device-width, initial-scale=1.0, viewport-fit=cover'))
const sources = []
for (const directory of ['src', 'public', 'pwa']) sources.push([directory, await inventory(path.join(frontend, directory))])
for (const file of ['package.json', 'package-lock.json', 'vite.config.ts']) sources.push([file, hash(await readFile(path.join(frontend, file)))])
const files = await inventory(web)
const receipt = { format: 'emcoin-native-bundle/v1', profile: 'emcoin-local-android/v1', applicationId: config.appId,
  api, sourceDigest: hash(JSON.stringify(sources)), hashRouter: true, native: true, serviceWorker: false, files }
validateStagingReceipt(receipt, files, port)
await writeFile(path.join(web, 'native-build.json'), JSON.stringify(receipt, null, 2))
await writeFile(path.join(output, 'qa.json'), JSON.stringify(receipt, null, 2))
await writeFile(path.join(output, 'assets/capacitor.config.json'), JSON.stringify(config))
await copyFile(path.join(project, 'native/android/app/src/main/assets/capacitor.plugins.json'), path.join(output, 'assets/capacitor.plugins.json'))
// Cert is generated by the fixture. Private key never enters assets/resources.
await copyFile(path.join(output, 'cert.pem'), path.join(resources, 'raw/emcoin_qa_ca.pem'))
await writeFile(path.join(resources, 'xml/emcoin_qa_security.xml'), `<?xml version="1.0" encoding="utf-8"?>
<network-security-config>
  <base-config cleartextTrafficPermitted="false"><trust-anchors><certificates src="system" /></trust-anchors></base-config>
  <domain-config cleartextTrafficPermitted="false"><domain includeSubdomains="false">10.0.2.2</domain><trust-anchors><certificates src="@raw/emcoin_qa_ca" /></trust-anchors></domain-config>
</network-security-config>`)
// Keep only public assets and certificate in the build resource tree.
if ((await inventory(path.join(output, 'assets'))).some(file => /\.pem$/i.test(file.file))) throw Error('QA_PRIVATE_FILE_IN_ASSETS')
console.log(`Owned Android staging inputs prepared: ${output}`)
